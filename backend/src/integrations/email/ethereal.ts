import nodemailer, { Transporter } from 'nodemailer';
import { env } from '../../config/env.js';
import { logger } from '../../config/logger.js';

let defaultTransporter: Transporter | null = null;
let etherealAccountInfo: { user: string; pass: string } | null = null;

export async function getOrCreateEtherealTransport(): Promise<{ transporter: Transporter; isAutoGenerated: boolean }> {
  if (defaultTransporter) {
    return { transporter: defaultTransporter, isAutoGenerated: !!etherealAccountInfo };
  }

  // Check if SMTP_USER and SMTP_PASS are provided in env
  if (env.SMTP_USER && env.SMTP_PASS) {
    defaultTransporter = nodemailer.createTransport({
      host: env.SMTP_HOST,
      port: env.SMTP_PORT,
      secure: env.SMTP_PORT === 465,
      auth: {
        user: env.SMTP_USER,
        pass: env.SMTP_PASS,
      },
    });
    logger.info({ host: env.SMTP_HOST, port: env.SMTP_PORT, user: env.SMTP_USER }, 'Configured SMTP transporter with provided credentials');
    return { transporter: defaultTransporter, isAutoGenerated: false };
  }

  // Otherwise, automatically generate an Ethereal test account on the fly!
  logger.info('Generating new Ethereal Email test account for local SMTP testing...');
  const testAccount = await nodemailer.createTestAccount();
  etherealAccountInfo = { user: testAccount.user, pass: testAccount.pass };

  defaultTransporter = nodemailer.createTransport({
    host: 'smtp.ethereal.email',
    port: 587,
    secure: false,
    auth: {
      user: testAccount.user,
      pass: testAccount.pass,
    },
  });

  logger.info(
    { user: testAccount.user, smtp: testAccount.smtp, web: testAccount.web },
    '✅ Ethereal test account created successfully!'
  );

  return { transporter: defaultTransporter, isAutoGenerated: true };
}

export async function verifyEmailTransport(): Promise<boolean> {
  try {
    const { transporter } = await getOrCreateEtherealTransport();
    await transporter.verify();
    logger.info('SMTP transport verified successfully');
    return true;
  } catch (error) {
    logger.error({ error }, 'SMTP transport verification failed');
    return false;
  }
}

export interface SendEmailOptions {
  from?: string;
  to: string;
  subject: string;
  html: string;
  text?: string;
  customTransporter?: Transporter;
}

export interface SendEmailResult {
  success: boolean;
  messageId?: string;
  previewUrl?: string | false;
  error?: string;
}

export async function sendEmail(options: SendEmailOptions): Promise<SendEmailResult> {
  const { transporter } = options.customTransporter
    ? { transporter: options.customTransporter }
    : await getOrCreateEtherealTransport();

  const fromAddress = options.from || (etherealAccountInfo ? etherealAccountInfo.user : env.SMTP_FROM);

  const info = await transporter.sendMail({
    from: fromAddress,
    to: options.to,
    subject: options.subject,
    html: options.html,
    text: options.text || options.html.replace(/<[^>]*>?/gm, ''),
  });

  const previewUrl = nodemailer.getTestMessageUrl(info);

  logger.info(
    { messageId: info.messageId, to: options.to, previewUrl: previewUrl || 'N/A' },
    'Email sent via Ethereal SMTP'
  );

  return {
    success: true,
    messageId: info.messageId,
    previewUrl: previewUrl || undefined,
  };
}
